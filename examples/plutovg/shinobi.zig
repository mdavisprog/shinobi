/// Represents a shorter name for reusable strings.
const Variable = struct {
    name: []const u8,
    value: []const u8,

    fn init(name: []const u8, value: []const u8) Variable {
        return .{ .name = name, .value = value };
    }

    fn deinit(self: Variable, allocator: std.mem.Allocator) void {
        allocator.free(self.name);
        allocator.free(self.value);
    }
};

/// Defines a short name for a command line.
const Rule = struct {
    name: []const u8,
    variables: std.StringHashMapUnmanaged(Variable),

    fn init(name: []const u8) Rule {
        return .{
            .name = name,
            .variables = .empty,
        };
    }

    fn deinit(self: *Rule, allocator: std.mem.Allocator) void {
        allocator.free(self.name);

        var it = self.variables.valueIterator();
        while (it.next()) |variable| {
            variable.deinit(allocator);
        }
        self.variables.deinit(allocator);
    }
};

/// Contains the relationship between input and output files.
const Build = struct {
    inputs: std.ArrayListUnmanaged([]const u8),
    outputs: std.ArrayListUnmanaged([]const u8),
    variables: std.StringHashMapUnmanaged(Variable),
    rule: ?[]const u8,

    fn init() Build {
        return .{
            .inputs = .empty,
            .outputs = .empty,
            .variables = .empty,
            .rule = null,
        };
    }

    fn deinit(self: *Build, allocator: std.mem.Allocator) void {
        for (self.inputs.items) |input| {
            allocator.free(input);
        }

        for (self.outputs.items) |output| {
            allocator.free(output);
        }

        self.inputs.deinit(allocator);
        self.outputs.deinit(allocator);

        if (self.rule) |rule| {
            allocator.free(rule);
        }

        var it = self.variables.valueIterator();
        while (it.next()) |variable| {
            variable.deinit(allocator);
        }
        self.variables.deinit(allocator);
    }
};

/// Represents a single output generated by a list of inputs.
const Artifact = struct {
    /// The type of artifact
    pub const Type = enum {
        object,
        library,
        executable,
        other,
    };

    /// List of artifacts
    pub const Collection = struct {
        list: std.ArrayListUnmanaged(Artifact) = .empty,

        fn deinit(self: *Collection, allocator: std.mem.Allocator) void {
            for (self.list.items) |*artifact| {
                artifact.deinit(allocator);
            }

            self.list.deinit(allocator);
        }

        fn add(self: *Collection, allocator: std.mem.Allocator, artifact: Artifact) !void {
            try self.list.append(allocator, artifact);
        }

        fn getByOutput(self: Collection, output: []const u8) ?Artifact {
            for (self.list.items) |artifact| {
                for (artifact.outputs.items) |item| {
                    if (std.mem.eql(u8, item, output)) {
                        return artifact;
                    }
                }
            }

            return null;
        }
    };

    output_type: Type = .object,
    inputs: std.ArrayListUnmanaged([]const u8) = .empty,
    outputs: std.ArrayListUnmanaged([]const u8) = .empty,
    flags: std.StringHashMapUnmanaged(void) = .empty,

    fn deinit(self: *Artifact, allocator: std.mem.Allocator) void {
        self.inputs.deinit(allocator);
        self.outputs.deinit(allocator);
        self.flags.deinit(allocator);
    }

    fn getOutputName(self: Artifact) []const u8 {
        if (self.outputs.items.len == 0) return switch (self.output_type) {
            .executable => "exe",
            .library => "module",
            .object => "object",
            .other => "other",
        };

        const stem = std.fs.path.stem(self.outputs.items[0]);
        if (std.mem.startsWith(u8, stem, "lib")) {
            return stem[3..];
        }

        return stem;
    }

    /// Caller owns the returned string.
    fn getValidOutputName(self: Artifact, allocator: std.mem.Allocator) ![]const u8 {
        const result = self.getOutputName();
        return try std.mem.replaceOwned(u8, allocator, result, "-", "_");
    }

    fn hasSameOutputs(self: Artifact, value: Artifact) bool {
        if (self.outputs.items.len != value.outputs.items.len) return false;

        for (0..self.outputs.items.len) |i| {
            if (!std.mem.eql(u8, self.outputs.items[i], value.outputs.items[i])) {
                return false;
            }
        }

        return true;
    }

    fn hasSameFlags(self: Artifact, value: Artifact) bool {
        if (self.flags.count() != value.flags.count()) return false;

        var it = self.flags.keyIterator();
        while (it.next()) |flag| {
            if (!value.flags.contains(flag.*)) {
                return false;
            }
        }

        return true;
    }
};

/// Struct to analyze a buffer stream to be parsed into tokens.
const Lexer = struct {
    /// List of possible tokens that can be lexed from a stream.
    const Token = struct {
        pub const Type = enum {
            build,
            rule,
            ident,
            equals,
            new_line,
            indent,
            colon,
            comment,
            include,
        };

        token_type: Type,
        data: []const u8,

        pub fn deinit(self: Token, allocator: std.mem.Allocator) void {
            allocator.free(self.data);
        }

        fn init(token_type: Type, data: []const u8) Token {
            return .{ .token_type = token_type, .data = data };
        }
    };

    /// Stores the buffer from where the lexer pulls bytes from.
    const Source = union(enum) {
        stream: std.Io.Reader,
        file: struct {
            handle: std.Io.File,
            buffer: []u8,
            reader: std.Io.File.Reader,
            path: []const u8,
        },

        fn initStream(stream: []const u8) Source {
            return .{ .stream = .fixed(stream) };
        }

        fn initFile(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !Source {
            const handle = if (std.fs.path.isAbsolute(path))
                try std.Io.Dir.openFileAbsolute(io, path, .{})
            else
                try std.Io.Dir.cwd().openFile(io, path, .{});

            const buffer = try allocator.alloc(u8, 1024);
            const reader = handle.reader(io, buffer);

            return .{
                .file = .{
                    .handle = handle,
                    .buffer = buffer,
                    .reader = reader,
                    .path = try allocator.dupe(u8, path),
                },
            };
        }

        fn deinit(self: *Source, allocator: std.mem.Allocator, io: std.Io) void {
            switch (self.*) {
                .stream => {},
                .file => |file| {
                    file.handle.close(io);
                    allocator.free(file.buffer);
                    allocator.free(file.path);
                },
            }
        }

        fn peekByte(self: *Source) !u8 {
            switch (self.*) {
                .stream => |*reader| {
                    return reader.peekByte();
                },
                .file => |*file| {
                    return file.reader.interface.peekByte();
                },
            }
        }

        fn toss(self: *Source, n: usize) void {
            switch (self.*) {
                .stream => |*reader| {
                    reader.toss(n);
                },
                .file => |*file| {
                    file.reader.interface.toss(n);
                },
            }
        }
    };

    source: Source,
    token: std.ArrayListUnmanaged(u8) = .empty,
    start_of_line: bool = true,

    fn initStream(stream: []const u8) Lexer {
        return .{
            .source = .initStream(stream),
        };
    }

    fn initFile(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !Lexer {
        return .{
            .source = try .initFile(allocator, io, path),
        };
    }

    fn deinit(self: *Lexer, allocator: std.mem.Allocator, io: std.Io) void {
        self.token.deinit(allocator);
        self.source.deinit(allocator, io);
    }

    fn nextToken(self: *Lexer, allocator: std.mem.Allocator) !?Token {
        self.token.clearRetainingCapacity();

        var is_escaped = false;
        var found_token = false;
        outer: while (true) : (self.source.toss(1)) {
            const ch = self.source.peekByte() catch |err| {
                if (err == error.EndOfStream) {
                    break :outer;
                }

                return err;
            };

            switch (ch) {
                ' ', '\t' => {
                    if (is_escaped) {
                        is_escaped = false;
                        try self.token.append(allocator, ch);
                        continue;
                    }

                    // This is an indentation
                    if (self.start_of_line) {
                        self.start_of_line = false;
                        while (true) {
                            const space = self.source.peekByte() catch |err| {
                                if (err == error.EndOfStream) {
                                    break;
                                }

                                return err;
                            };

                            if (space != ' ' and space != '\t') {
                                return .init(.indent, "");
                            }

                            self.source.toss(1);
                        }
                    }

                    if (!found_token) {
                        continue;
                    } else {
                        break :outer;
                    }
                },
                '\r' => {
                    continue;
                },
                '\n', ':' => {
                    if (is_escaped) {
                        is_escaped = false;

                        if (ch == ':') {
                            try self.token.append(allocator, ch);
                        }
                    } else {
                        if (!found_token) {
                            found_token = true;
                            try self.token.append(allocator, ch);
                            self.source.toss(1);
                        }

                        break :outer;
                    }
                },
                '#' => {
                    try self.token.append(allocator, ch);

                    if (self.start_of_line) {
                        self.source.toss(1);

                        while (true) {
                            const next = self.source.peekByte() catch |err| {
                                if (err == error.EndOfStream) {
                                    break :outer;
                                }

                                return err;
                            };

                            if (next != '\n') {
                                try self.token.append(allocator, next);
                                self.source.toss(1);
                            } else {
                                break :outer;
                            }
                        }
                    }
                },
                '$' => {
                    self.start_of_line = false;
                    found_token = true;
                    is_escaped = true;
                    try self.token.append(allocator, ch);
                },
                else => {
                    self.start_of_line = false;
                    found_token = true;
                    is_escaped = false;
                    try self.token.append(allocator, ch);
                },
            }
        }

        const slice = try self.token.toOwnedSlice(allocator);

        if (std.mem.eql(u8, slice, "build")) {
            return .init(.build, slice);
        } else if (std.mem.eql(u8, slice, "rule")) {
            return .init(.rule, slice);
        } else if (std.mem.eql(u8, slice, "=")) {
            return .init(.equals, slice);
        } else if (std.mem.eql(u8, slice, "\n")) {
            self.start_of_line = true;
            return .init(.new_line, slice);
        } else if (std.mem.eql(u8, slice, ":")) {
            return .init(.colon, slice);
        } else if (std.mem.eql(u8, slice, "include")) {
            return .init(.include, slice);
        } else if (std.mem.startsWith(u8, slice, "#")) {
            return .init(.comment, slice);
        } else if (slice.len > 0) {
            return .init(.ident, slice);
        }

        return null;
    }

    fn getPath(self: Lexer) ?[]const u8 {
        return switch (self.source) {
            .stream => null,
            .file => |file| file.path,
        };
    }
};

/// Parses a stream or file into tokens so they can be destructured to create a 'build.zig' file.
const Parser = struct {
    pub const Error = error{
        InvalidRule,
        InvalidInclude,
    };

    lexer: Lexer,
    variables: std.StringHashMapUnmanaged(Variable) = .empty,
    rules: std.StringHashMapUnmanaged(Rule) = .empty,
    builds: std.ArrayListUnmanaged(Build) = .empty,

    fn initStream(stream: []const u8) Parser {
        return .{
            .lexer = .initStream(stream),
        };
    }

    fn initFile(allocator: std.mem.Allocator, io: std.Io, path: []const u8) !Parser {
        return .{
            .lexer = try .initFile(allocator, io, path),
        };
    }

    fn deinit(self: *Parser, allocator: std.mem.Allocator, io: std.Io) void {
        {
            var it = self.variables.valueIterator();
            while (it.next()) |variable| {
                variable.deinit(allocator);
            }
            self.variables.deinit(allocator);
        }

        {
            var it = self.rules.valueIterator();
            while (it.next()) |rule| {
                rule.deinit(allocator);
            }
            self.rules.deinit(allocator);
        }

        for (self.builds.items) |*build| {
            build.deinit(allocator);
        }
        self.builds.deinit(allocator);

        self.lexer.deinit(allocator, io);
    }

    fn begin(self: *Parser, allocator: std.mem.Allocator, io: std.Io) anyerror!void {
        var last_token: ?Lexer.Token = null;
        defer if (last_token) |token| token.deinit(allocator);

        while (try self.lexer.nextToken(allocator)) |token| {
            switch (token.token_type) {
                .equals => {
                    const last = last_token orelse unreachable;
                    const variable = try self.parseVariable(allocator, last);
                    try self.variables.put(allocator, variable.name, variable);
                },
                .rule => {
                    const rule = try self.parseRule(allocator);
                    try self.rules.put(allocator, rule.name, rule);
                },
                .build => {
                    const build = try self.parseBuild(allocator);
                    try self.builds.append(allocator, build);
                },
                .include => {
                    try self.parseInclude(allocator, io);
                },
                else => {},
            }

            if (last_token) |last| last.deinit(allocator);
            last_token = token;
        }
    }

    fn printSummary(self: Parser) void {
        {
            std.log.info("Variables: {}", .{self.variables.count()});

            var it = self.variables.valueIterator();
            while (it.next()) |variable| {
                std.log.info("   {s} = {s}", .{ variable.name, variable.value });
            }
        }

        {
            std.log.info("Rules: {}", .{self.rules.count()});
            var it = self.rules.valueIterator();
            while (it.next()) |rule| {
                std.log.info("   {s} has {} variables", .{ rule.name, rule.variables.count() });

                var variables = rule.variables.valueIterator();
                while (variables.next()) |variable| {
                    std.log.info("      {s} = {s}", .{ variable.name, variable.value });
                }
            }
        }

        {
            std.log.info("Builds: {}", .{self.builds.items.len});
            for (self.builds.items) |build| {
                std.log.info("   inputs: {}", .{build.inputs.items.len});
                for (build.inputs.items) |input| {
                    std.log.info("      {s}", .{input});
                }

                std.log.info("   outputs: {}", .{build.outputs.items.len});
                for (build.outputs.items) |output| {
                    std.log.info("      {s}", .{output});
                }

                if (build.rule) |rule| {
                    std.log.info("   Rule: {s}", .{rule});
                }

                std.log.info("   variables: {}", .{build.variables.count()});
                var variables = build.variables.valueIterator();
                while (variables.next()) |variable| {
                    std.log.info("      {s} = {s}", .{ variable.name, variable.value });
                }
            }
        }
    }

    fn parseVariable(self: *Parser, allocator: std.mem.Allocator, name_token: Lexer.Token) !Variable {
        var value = std.ArrayListUnmanaged(u8).empty;

        var single_token = false;
        while (try self.lexer.nextToken(allocator)) |token| {
            defer token.deinit(allocator);

            switch (token.token_type) {
                .ident, .build => {
                    if (value.items.len > 0 and !single_token) {
                        try value.append(allocator, ' ');
                    }

                    try value.appendSlice(allocator, token.data);
                    single_token = false;
                },
                // ':' token is not escaped in variables. Add these tokens and mark
                // identifier as a single token.
                .colon => {
                    try value.appendSlice(allocator, token.data);
                    single_token = true;
                },
                else => break,
            }
        }

        return .init(
            try allocator.dupe(u8, name_token.data),
            try value.toOwnedSlice(allocator),
        );
    }

    fn parseVariableBlock(
        self: *Parser,
        allocator: std.mem.Allocator,
        variables: *std.StringHashMapUnmanaged(Variable),
    ) !void {
        var last_token: ?Lexer.Token = null;
        defer if (last_token) |token| token.deinit(allocator);

        var parsing_variable = false;
        outer: while (try self.lexer.nextToken(allocator)) |token| {
            switch (token.token_type) {
                .equals => {
                    const last = last_token orelse return Error.InvalidRule;
                    const variable = try self.parseVariable(allocator, last);
                    try variables.put(allocator, variable.name, variable);
                    // The 'parseVariable' function will eat the '\n' token so need to mark
                    // flag as false.
                    parsing_variable = false;
                },
                .indent => {
                    parsing_variable = true;
                },
                .new_line => {
                    if (!parsing_variable) {
                        token.deinit(allocator);
                        break :outer;
                    } else {
                        parsing_variable = false;
                    }
                },
                else => {},
            }

            if (last_token) |last| last.deinit(allocator);
            last_token = token;
        }
    }

    fn parseRule(self: *Parser, allocator: std.mem.Allocator) !Rule {
        const name = try self.lexer.nextToken(allocator) orelse return Error.InvalidRule;
        defer name.deinit(allocator);
        if (name.token_type != .ident) return Error.InvalidRule;

        var rule = Rule.init(try allocator.dupe(u8, name.data));
        errdefer rule.deinit(allocator);

        const new_line = try self.lexer.nextToken(allocator) orelse return Error.InvalidRule;
        defer new_line.deinit(allocator);
        if (new_line.token_type != .new_line) return Error.InvalidRule;

        try self.parseVariableBlock(allocator, &rule.variables);

        return rule;
    }

    fn parseBuild(self: *Parser, allocator: std.mem.Allocator) !Build {
        var build = Build.init();
        errdefer build.deinit(allocator);

        var parsing_outputs = true;
        var parsing_rule = true;
        outer: while (try self.lexer.nextToken(allocator)) |token| {
            defer token.deinit(allocator);

            switch (token.token_type) {
                .ident => {
                    if (parsing_outputs) {
                        try build.outputs.append(allocator, try allocator.dupe(u8, token.data));
                    } else {
                        if (parsing_rule) {
                            build.rule = try allocator.dupe(u8, token.data);
                            parsing_rule = false;
                        } else {
                            const input = try std.mem.replaceOwned(u8, allocator, token.data, "$", "");
                            std.mem.replaceScalar(u8, input, '\\', '/');
                            try build.inputs.append(allocator, input);
                        }
                    }
                },
                .colon => {
                    parsing_outputs = false;
                },
                else => {
                    break :outer;
                },
            }
        }

        try self.parseVariableBlock(allocator, &build.variables);

        return build;
    }

    fn parseInclude(self: *Parser, allocator: std.mem.Allocator, io: std.Io) anyerror!void {
        const path_token = try self.lexer.nextToken(allocator) orelse return Error.InvalidInclude;
        defer path_token.deinit(allocator);

        if (self.lexer.getPath()) |path| {
            if (std.fs.path.dirname(path)) |dir| {
                const include_path = try std.fs.path.join(allocator, &.{ dir, path_token.data });
                defer allocator.free(include_path);

                var parser = try Parser.initFile(allocator, io, include_path);

                try parser.begin(allocator, io);
                try self.move(allocator, parser);

                // We do not want to free the allocated elements as they have been moved.
                // Just free the containers.
                parser.variables.deinit(allocator);
                parser.rules.deinit(allocator);
                parser.builds.deinit(allocator);
                parser.lexer.deinit(allocator, io);
            }
        } else {
        }
    }

    fn move(self: *Parser, allocator: std.mem.Allocator, other: Parser) !void {
        // Move variables
        {
            var it = other.variables.valueIterator();
            while (it.next()) |variable| {
                try self.variables.put(allocator, variable.name, variable.*);
            }
        }

        // Move rules
        {
            var it = other.rules.valueIterator();
            while (it.next()) |rule| {
                try self.rules.put(allocator, rule.name, rule.*);
            }
        }

        // Move builds
        {
            try self.builds.appendSlice(allocator, other.builds.items);
        }
    }
};

/// Manages parsing a 'ninja' file and emitting a 'build.zig' file.
const Generator = struct {
    /// List of possible errors.
    const Error = error{
        InvalidRule,
    };

    fn add(
        self: Generator,
        b: *std.Build,
        path: []const u8,
        options: Options,
    ) !void {
        _ = self;

        const allocator = b.allocator;
        const io = b.graph.io;

        const resolved_path = try resolvePath(allocator, io, path, options);
        defer b.allocator.free(resolved_path);

        std.log.info("Attempting to parse ninja file '{s}'", .{resolved_path});

        var parser = try Parser.initFile(allocator, io, resolved_path);
        defer parser.deinit(allocator, io);

        try parser.begin(allocator, io);

        var artifacts = try gatherArtifacts(allocator, parser);
        defer artifacts.deinit(allocator);

        // Add all libraries first
        for (artifacts.list.items) |artifact| {
            if (artifact.output_type != .library) continue;

            try addModule(b, artifact, artifacts, b.build_root.path.?, options);
        }

        // Add all executables next
        for (artifacts.list.items) |artifact| {
            if (artifact.output_type != .executable) continue;

            try addExecutable(b, artifact, artifacts, b.build_root.path.?, options);
        }
    }

    fn generate(
        self: Generator,
        allocator: std.mem.Allocator,
        io: std.Io,
        path: []const u8,
        options: Options,
    ) !void {
        _ = self;

        const resolved_path = try resolvePath(allocator, io, path, options);
        defer allocator.free(resolved_path);

        std.log.info("Attempting to parse ninja file '{s}'", .{resolved_path});

        var parser = try Parser.initFile(allocator, io, resolved_path);
        defer parser.deinit(allocator, io);

        try parser.begin(allocator, io);

        std.log.info("Generating 'build.zig' file", .{});

        const dir = std.fs.path.dirname(resolved_path) orelse {
            std.log.err("Failed to retrieve directory of ninja file '{s}'!", .{resolved_path});
            return;
        };

        const absolute_dir = try std.Io.Dir.cwd().realPathFileAlloc(io, dir, allocator);
        defer allocator.free(absolute_dir);

        const output_path = try std.fs.path.join(allocator, &.{ dir, "build.zig" });
        defer allocator.free(output_path);

        var artifacts = try gatherArtifacts(allocator, parser);
        defer artifacts.deinit(allocator);

        const file = if (std.fs.path.isAbsolute(output_path))
            try std.Io.Dir.createFileAbsolute(io, output_path, .{})
        else
            try std.Io.Dir.cwd().createFile(io, output_path, .{});
        defer file.close(io);

        var buffer: [1024]u8 = undefined;
        var writer = file.writer(io, &buffer);

        try writeHeader(&writer.interface);
        try writeBuildVars(&writer.interface);
        try writeArtifacts(allocator, &writer.interface, artifacts, absolute_dir);
        try writeFooter(&writer.interface);

        if (options.print_summary) {
            parser.printSummary();
        }
    }

    fn gatherArtifacts(allocator: std.mem.Allocator, parser: Parser) !Artifact.Collection {
        var artifacts = Artifact.Collection{};

        for (parser.builds.items) |build| {
            var artifact = Artifact{};
            artifact.output_type = .other;
            artifact.flags = try getFlags(allocator, build, parser);

            var has_compile_command = false;
            var has_link_command = false;
            var has_clang_command = false;

            var it = artifact.flags.keyIterator();
            while (it.next()) |flag| {
                if (std.mem.eql(u8, flag.*, "-c")) {
                    has_compile_command = true;
                }

                if (std.mem.eql(u8, flag.*, "cmake_llvm_rc")) {
                    has_compile_command = true;
                }

                if (std.mem.containsAtLeast(u8, flag.*, 1, "llvm-ar")) {
                    has_link_command = true;
                }

                if (std.mem.containsAtLeast(u8, flag.*, 1, "bin/ar")) {
                    has_link_command = true;
                }

                if (std.mem.containsAtLeast(u8, flag.*, 1, "clang")) {
                    has_clang_command = true;
                }
            }

            artifact.output_type = if (has_compile_command)
                .object
            else if (has_link_command)
                .library
            else if (has_clang_command)
                .executable
            else
                .other;

            for (build.inputs.items) |input| {
                switch (artifact.output_type) {
                    .object => {
                        if (isValidSourceFile(input)) {
                            try artifact.inputs.append(allocator, input);
                        }
                    },
                    else => {
                        try artifact.inputs.append(allocator, input);
                    },
                }
            }

            if (artifact.inputs.items.len == 0) {
                artifact.deinit(allocator);
                continue;
            }

            for (build.outputs.items) |output| {
                try artifact.outputs.append(allocator, output);
            }

            it = artifact.flags.keyIterator();
            while (it.next()) |flag| {
                if (!isValidFlag(flag.*)) {
                    _ = artifact.flags.remove(flag.*);
                }
            }

            try artifacts.add(allocator, artifact);
        }

        return artifacts;
    }

    fn getFlags(
        allocator: std.mem.Allocator,
        build: Build,
        parser: Parser,
    ) !std.StringHashMapUnmanaged(void) {
        var flags = std.StringHashMapUnmanaged(void).empty;

        const command = getVariable("command", build, parser) orelse return flags;

        try parseFlags(allocator, command.value, &flags);

        var tokens = std.mem.tokenizeAny(u8, command.value, " ");
        while (tokens.next()) |token| {
            if (std.mem.startsWith(u8, token, "$")) {
                const name = token[1..];

                const variable = getVariable(name, build, parser) orelse continue;
                try parseFlags(allocator, variable.value, &flags);
            }
        }

        return flags;
    }

    fn parseFlags(
        allocator: std.mem.Allocator,
        stream: []const u8,
        flags: *std.StringHashMapUnmanaged(void),
    ) !void {
        var tokens = std.mem.tokenizeAny(u8, stream, " ");
        while (tokens.next()) |token| {
            try flags.put(allocator, token, {});
        }
    }

    fn writeHeader(writer: *std.Io.Writer) !void {
        try writer.print("const std = @import(\"std\");\n", .{});
        try writer.print("\n", .{});
        try writer.print("pub fn build(b: *std.Build) !void {{\n", .{});
        try writer.flush();
    }

    fn writeFooter(writer: *std.Io.Writer) !void {
        try writer.print("}}\n", .{});
        try writer.flush();
    }

    fn writeBuildVars(writer: *std.Io.Writer) !void {
        try writer.print("    const target = b.standardTargetOptions(.{{}});\n", .{});
        try writer.print("    const optimize = b.standardOptimizeOption(.{{}});\n\n", .{});
        try writer.flush();
    }

    fn writeAddModule(writer: *std.Io.Writer, name: []const u8) !void {
        try writer.print("    const {s} = b.addModule(\"{s}\", .{{\n", .{ name, name });
        try writer.print("        .target = target,\n", .{});
        try writer.print("        .optimize = optimize,\n", .{});
        try writer.print("    }});\n", .{});
        try writer.flush();
    }

    fn writeAddExecutable(writer: *std.Io.Writer, name: []const u8) !void {
        try writer.print("    const {s} = b.addExecutable(.{{\n", .{name});
        try writer.print("        .name = \"{s}\",\n", .{name});
        try writer.print("        .root_module = b.createModule(.{{\n", .{});
        try writer.print("            .target = target,\n", .{});
        try writer.print("            .optimize = optimize,\n", .{});
        try writer.print("            .link_libc = true,\n", .{});
        try writer.print("        }}),\n", .{});
        try writer.print("    }});\n", .{});
        try writer.flush();
    }

    fn writeArtifacts(
        allocator: std.mem.Allocator,
        writer: *std.Io.Writer,
        artifacts: Artifact.Collection,
        build_dir: []const u8,
    ) !void {
        // Write all libraries first
        for (artifacts.list.items) |artifact| {
            if (artifact.output_type != .library) continue;

            try writeArtifact(allocator, writer, artifact, artifacts, build_dir);
            try writer.print("\n", .{});
        }

        // Write all executables next
        for (artifacts.list.items) |artifact| {
            if (artifact.output_type != .executable) continue;

            try writeArtifact(allocator, writer, artifact, artifacts, build_dir);
        }
    }

    fn writeArtifact(
        allocator: std.mem.Allocator,
        writer: *std.Io.Writer,
        artifact: Artifact,
        artifacts: Artifact.Collection,
        build_dir: []const u8,
    ) !void {
        const name = try artifact.getValidOutputName(allocator);
        defer allocator.free(name);

        switch (artifact.output_type) {
            .executable => {
                try writeAddExecutable(writer, name);
            },
            .library => {
                try writeAddModule(writer, name);
            },
            else => return,
        }

        var input_artifacts = try getInputArtifacts(allocator, artifact, artifacts);
        defer input_artifacts.deinit(allocator);

        var written = std.ArrayListUnmanaged(Artifact).empty;
        defer written.deinit(allocator);

        var includes = std.ArrayListUnmanaged([]const u8).empty;
        defer includes.deinit(allocator);

        outer: for (input_artifacts.items) |input_artifact| {
            var flags = input_artifact.flags.keyIterator();
            while (flags.next()) |flag| {
                if (!std.mem.startsWith(u8, flag.*, "-I")) {
                    continue;
                }

                const path = flag.*[2..];

                var found = false;
                for (includes.items) |include| {
                    if (std.mem.eql(u8, path, include)) {
                        found = true;
                        break;
                    }
                }

                if (!found) {
                    try includes.append(allocator, path);
                }
            }

            for (written.items) |item| {
                if (item.hasSameOutputs(input_artifact)) continue :outer;
            }

            try writer.print("    {s}{s}.addCSourceFiles(.{{\n", .{
                name,
                if (artifact.output_type == .executable) ".root_module" else "",
            });
            try writer.print("        .files = &.{{\n", .{});
            try writer.flush();

            try writeInputs(allocator, writer, input_artifact, build_dir);
            try written.append(allocator, input_artifact);

            for (input_artifacts.items) |inner| {
                if (input_artifact.hasSameOutputs(inner)) continue;

                if (input_artifact.hasSameFlags(inner)) {
                    try writeInputs(allocator, writer, inner, build_dir);
                    try written.append(allocator, inner);
                }
            }

            try writer.print("        }},\n", .{});
            try writer.print("        .flags = &.{{\n", .{});

            var it = input_artifact.flags.keyIterator();
            while (it.next()) |flag| {
                if (std.mem.startsWith(u8, flag.*, "-I")) {
                    continue;
                }

                try writer.print("            \"{s}\",\n", .{flag.*});
                try writer.flush();
            }

            try writer.print("        }},\n", .{});
            try writer.print("    }});\n", .{});
            try writer.flush();

            try writeImports(allocator, writer, artifact);
        }

        for (includes.items) |include| {
            const relative = try std.fs.path.relative(allocator, ".", null, build_dir, include);
            defer allocator.free(relative);

            std.mem.replaceScalar(u8, relative, '\\', '/');

            try writer.print("    {s}{s}.addIncludePath(b.path(\"{s}\"));\n", .{
                name,
                if (artifact.output_type == .executable) ".root_module" else "",
                relative,
            });
        }

        if (artifact.output_type == .executable) {
            try writer.print("    b.installArtifact({s});\n", .{name});
            try writer.flush();
        }
    }

    fn writeInputs(
        allocator: std.mem.Allocator,
        writer: *std.Io.Writer,
        artifact: Artifact,
        build_dir: []const u8,
    ) !void {
        for (artifact.inputs.items) |file| {
            const relative = try std.fs.path.relative(allocator, ".", null, build_dir, file);
            defer allocator.free(relative);

            std.mem.replaceScalar(u8, relative, '\\', '/');

            try writer.print("            \"{s}\",\n", .{relative});
            try writer.flush();
        }
    }

    fn writeImports(
        allocator: std.mem.Allocator,
        writer: *std.Io.Writer,
        artifact: Artifact,
    ) !void {
        switch (artifact.output_type) {
            .executable, .library => {},
            else => return,
        }

        var added = std.StringHashMapUnmanaged(void).empty;
        defer added.deinit(allocator);

        const output_name = try artifact.getValidOutputName(allocator);
        defer allocator.free(output_name);

        for (artifact.inputs.items) |input| {
            const ext = std.fs.path.extension(input);
            if (std.mem.eql(u8, ext, ".lib") or std.mem.eql(u8, ext, ".a")) {
                const name = std.fs.path.stem(input);

                if (added.contains(name)) continue;
                try added.put(allocator, name, {});

                try writer.print("    {s}{s}.addImport(\"{s}\", {s});\n", .{
                    output_name,
                    if (artifact.output_type == .executable) ".root_module" else "",
                    name,
                    name,
                });
            }
        }
    }

    fn isValidSourceFile(file: []const u8) bool {
        const stem = std.fs.path.stem(file);
        if (std.mem.eql(u8, stem, "CMakeCCompilerABI") or
            std.mem.eql(u8, stem, "CMakeCXXCompilerABI"))
        {
            return false;
        }

        const ext = std.fs.path.extension(file);
        if (!(std.mem.eql(u8, ext, ".c") or std.mem.eql(u8, ext, ".cpp"))) {
            return false;
        }

        return true;
    }

    fn isValidFlag(flag: []const u8) bool {
        if (!(std.mem.startsWith(u8, flag, "-") or std.mem.startsWith(u8, flag, "/"))) {
            return false;
        }

        // Ignore 'compile' and 'output' flag
        if (std.mem.eql(u8, flag, "-c")) return false;
        if (std.mem.eql(u8, flag, "-o")) return false;
        if (std.mem.eql(u8, flag, "-D_MT")) return false;
        if (std.mem.eql(u8, flag, "-O3")) return false;
        if (std.mem.eql(u8, flag, "-MT")) return false;
        if (std.mem.eql(u8, flag, "-Xclang")) return false;
        if (std.mem.eql(u8, flag, "-D_DLL")) return false;
        if (std.mem.eql(u8, flag, "-DNDEBUG")) return false;
        if (std.mem.eql(u8, flag, "-MD")) return false;
        if (std.mem.eql(u8, flag, "-MF")) return false;

        if (std.mem.startsWith(u8, flag, "--dependent-lib")) return false;

        return true;
    }

    fn getVariable(name: []const u8, build: Build, parser: Parser) ?Variable {
        if (build.variables.get(name)) |variable| {
            return variable;
        }

        const rule_name = build.rule orelse return null;
        const rule = parser.rules.get(rule_name) orelse return null;
        if (rule.variables.get(name)) |variable| {
            return variable;
        }

        if (parser.variables.get(name)) |variable| {
            return variable;
        }

        return null;
    }

    fn resolvePath(
        allocator: std.mem.Allocator,
        io: std.Io,
        path: []const u8,
        options: Options,
    ) ![]const u8 {
        // Check if given path is a 'build.ninja' file or a directory.
        const extension = std.fs.path.extension(path);
        if (std.mem.eql(u8, extension, ".ninja")) {
            return allocator.dupe(u8, path);
        } else {
            const open_options = std.Io.Dir.OpenOptions{ .iterate = true };
            const dir = if (std.fs.path.isAbsolute(path))
                try std.Io.Dir.openDirAbsolute(io, path, open_options)
            else
                try std.Io.Dir.cwd().openDir(io, path, open_options);

            defer dir.close(io);

            var it = dir.iterate();
            while (try it.next(io)) |entry| {
                if (entry.kind != .file) continue;

                if (std.mem.eql(u8, entry.name, "build.ninja")) {
                    std.log.info("Found 'build.ninja' file in given path.", .{});
                    return std.fs.path.join(allocator, &.{ path, entry.name });
                } else if (std.mem.eql(u8, entry.name, "CMakeLists.txt")) {
                    const cmake_options = cmake.CMakeOptions{
                        .build_type = .fromOptimizeMode(options.configuration),
                        .bin_path = options.cmake_bin_path,
                    };
                    const result = try cmake.generate(
                        allocator,
                        io,
                        path,
                        cmake_options,
                    );

                    return result.ninja_path orelse std.Io.File.OpenError.FileNotFound;
                }
            }
        }

        return std.Io.File.OpenError.FileNotFound;
    }

    fn getInputArtifacts(
        allocator: std.mem.Allocator,
        artifact: Artifact,
        artifacts: Artifact.Collection,
    ) !std.ArrayListUnmanaged(Artifact) {
        var result = std.ArrayListUnmanaged(Artifact).empty;

        outer: for (artifact.inputs.items) |input| {
            const input_artifact = artifacts.getByOutput(input) orelse continue;
            if (input_artifact.inputs.items.len == 0) continue;

            for (input_artifact.inputs.items) |file| {
                if (!isValidSourceFile(file)) continue :outer;
            }

            try result.append(allocator, input_artifact);
        }

        return result;
    }

    fn addModule(
        b: *std.Build,
        artifact: Artifact,
        artifacts: Artifact.Collection,
        build_dir: []const u8,
        options: Options,
    ) !void {
        if (artifact.output_type != .library) return;

        const module = b.addModule(artifact.getOutputName(), .{
            .target = options.target,
            .optimize = options.configuration,
        });

        try addSourceFiles(module, artifact, artifacts, build_dir);
    }

    fn addExecutable(
        b: *std.Build,
        artifact: Artifact,
        artifacts: Artifact.Collection,
        build_dir: []const u8,
        options: Options,
    ) !void {
        if (artifact.output_type != .executable) return;

        const exe = b.addExecutable(.{
            .name = artifact.getOutputName(),
            .root_module = b.createModule(.{
                .target = options.target,
                .optimize = options.configuration,
            }),
        });

        try addSourceFiles(exe.root_module, artifact, artifacts, build_dir);
    }

    fn addSourceFiles(
        module: *std.Build.Module,
        artifact: Artifact,
        artifacts: Artifact.Collection,
        build_dir: []const u8,
    ) !void {
        const allocator = module.owner.allocator;

        var input_artifacts = try getInputArtifacts(allocator, artifact, artifacts);
        defer input_artifacts.deinit(allocator);

        var includes = std.ArrayListUnmanaged([]const u8).empty;
        defer includes.deinit(allocator);

        var written = std.ArrayListUnmanaged(Artifact).empty;
        defer written.deinit(allocator);

        var files = std.ArrayListUnmanaged([]const u8).empty;
        var flags = std.ArrayListUnmanaged([]const u8).empty;

        outer: for (input_artifacts.items) |input_artifact| {
            var it = input_artifact.flags.keyIterator();
            while (it.next()) |flag| {
                if (!std.mem.startsWith(u8, flag.*, "-I")) {
                    continue;
                }

                const path = flag.*[2..];

                var found = false;
                for (includes.items) |include| {
                    if (std.mem.eql(u8, path, include)) {
                        found = true;
                        break;
                    }
                }

                if (!found) {
                    try includes.append(allocator, path);
                }
            }

            for (written.items) |item| {
                if (item.hasSameOutputs(input_artifact)) continue :outer;
            }

            try written.append(allocator, input_artifact);
            try gatherSourceFiles(allocator, &files, input_artifact, build_dir);

            for (input_artifacts.items) |inner| {
                if (input_artifact.hasSameOutputs(inner)) continue;

                if (input_artifact.hasSameFlags(inner)) {
                    try written.append(allocator, inner);
                    try gatherSourceFiles(allocator, &files, inner, build_dir);
                }
            }

            it = input_artifact.flags.keyIterator();
            while (it.next()) |flag| {
                if (std.mem.startsWith(u8, flag.*, "-I")) {
                    continue;
                }

                try flags.append(allocator, flag.*);
            }
        }

        module.link_libc = true;
        module.addCSourceFiles(.{
            .files = try files.toOwnedSlice(allocator),
            .flags = try flags.toOwnedSlice(allocator),
        });

        for (includes.items) |include| {
            const relative = try std.fs.path.relative(allocator, ".", null, build_dir, include);
            module.addIncludePath(module.owner.path(relative));
        }
    }

    fn gatherSourceFiles(
        allocator: std.mem.Allocator,
        files: *std.ArrayListUnmanaged([]const u8),
        artifact: Artifact,
        build_dir: []const u8,
    ) !void {
        for (artifact.inputs.items) |file| {
            const relative = try std.fs.path.relative(allocator, ".", null, build_dir, file);
            try files.append(allocator, relative);
        }
    }
};

const cmake = struct {
    /// The build directory where cmake artifacts will be written.
    const build_path = "Build";

    /// Represents the configuration to be passed in via '-DCMAKE_BUILD_TYPE'.
    const BuildType = enum {
        debug,
        release,
        rel_with_deb_info,
        min_size_rel,
        custom,

        fn fromOptimizeMode(mode: std.builtin.OptimizeMode) BuildType {
            return switch (mode) {
                .Debug => .debug,
                else => .release,
            };
        }

        fn toStr(self: BuildType) []const u8 {
            return switch (self) {
                .debug => "Debug",
                .release => "Release",
                .rel_with_deb_info => "RelWithDebInfo",
                .min_size_rel => "MinSizeRel",
                .custom => "",
            };
        }
    };

    /// List of options for controlling 'cmake' to generate a 'build.ninja' file.
    const CMakeOptions = struct {
        /// The build type to use
        build_type: BuildType = .release,

        /// Path containing the cmake executable
        bin_path: ?[]const u8 = null,

        /// Should more information about the 'cmake' command execution be printed?
        verbose: bool = false,
    };

    /// Result from generating a 'build.ninja' using 'cmake'.
    const GenerateResult = struct {
        const fail = GenerateResult{};

        /// Did it succeed?
        success: bool = false,

        /// The caller owns this memory. Uses same allocator given to function.
        /// The path to the generated 'build.ninja' file.
        ninja_path: ?[]const u8 = null,

        fn deinit(self: GenerateResult, allocator: std.mem.Allocator) void {
            allocator.free(self.ninja_path);
        }
    };

    /// List of arguments to be passed to the 'cmake' command. Keeps track of arguments
    /// that needed a memory allocation will be properly freed on 'deinit'.
    const Arguments = struct {
        allocator: std.mem.Allocator,
        list: std.ArrayListUnmanaged([]const u8) = .empty,
        free: std.ArrayListUnmanaged(usize) = .empty,

        fn init(allocator: std.mem.Allocator) Arguments {
            return .{ .allocator = allocator };
        }

        fn deinit(self: *Arguments) void {
            for (self.free.items) |index| {
                self.allocator.free(self.list.items[index]);
            }

            self.list.deinit(self.allocator);
            self.free.deinit(self.allocator);
        }

        fn append(self: *Arguments, arg: []const u8) !void {
            try self.list.append(self.allocator, arg);
        }

        fn appendFormat(self: *Arguments, comptime fmt: []const u8, args: anytype) !void {
            const buffer = try std.fmt.allocPrint(self.allocator, fmt, args);
            try self.list.append(self.allocator, buffer);
            try self.free.append(self.allocator, self.list.items.len - 1);
        }
    };

    fn generate(
        allocator: std.mem.Allocator,
        io: std.Io,
        path: []const u8,
        options: CMakeOptions,
    ) !GenerateResult {
        std.log.info("Running 'cmake' to generate 'build.ninja' file.", .{});

        var arguments = Arguments.init(allocator);
        defer arguments.deinit();

        const bin_path = options.bin_path orelse "";
        try arguments.appendFormat("{s}{s}", .{ bin_path, exeName() });
        try arguments.append("-G Ninja");
        try arguments.append("-B");
        try arguments.appendFormat("{s}/{s}", .{ path, build_path });
        try arguments.append("-S");
        try arguments.append(path);
        try arguments.append("'-DCMAKE_C_COMPILER=zig cc'");
        try arguments.append("'-DCMAKE_CXX_COMPILER=zig c++'");
        try arguments.append("-DCMAKE_MAKE_PROGRAM=ninja");
        try arguments.appendFormat("-DCMAKE_BUILD_TYPE={s}", .{options.build_type.toStr()});

        var command = std.ArrayListUnmanaged(u8).empty;
        defer command.deinit(allocator);

        for (arguments.list.items) |arg| {
            try command.appendSlice(allocator, arg);
            try command.append(allocator, ' ');
        }

        std.log.info("Running command '{s}'", .{command.items});

        const result = std.process.run(allocator, io, .{
            .argv = arguments.list.items,
        }) catch |err| {
            switch (err) {
                std.process.RunError.FileNotFound => {
                    std.log.err("'cmake' executable was not found!", .{});
                    return .fail;
                },
                else => return err,
            }
        };
        defer allocator.free(result.stdout);
        defer allocator.free(result.stderr);

        const dir_or_error = if (std.fs.path.isAbsolute(path))
            std.Io.Dir.openDirAbsolute(io, path, .{})
        else
            std.Io.Dir.cwd().openDir(io, path, .{});

        const dir = dir_or_error catch {
            printResult(result);
            return .fail;
        };
        defer dir.close(io);

        dir.access(io, build_path ++ "/build.ninja", .{}) catch |err| {
            std.log.err("Failed to generate 'build.ninja' file: {}", .{err});
            printResult(result);
            return .fail;
        };

        if (result.term != .exited or options.verbose) {
            printResult(result);
        }

        return .{
            .success = true,
            .ninja_path = try std.fmt.allocPrint(allocator, "{s}/{s}/build.ninja", .{ path, build_path }),
        };
    }

    fn exeName() []const u8 {
        return switch (builtin.os.tag) {
            .windows => "cmake.exe",
            else => "cmake",
        };
    }

    fn printResult(result: std.process.RunResult) void {
        std.log.warn("stdout\n{s}", .{result.stdout});
        std.log.err("stderr\n{s}", .{result.stderr});
    }
};

